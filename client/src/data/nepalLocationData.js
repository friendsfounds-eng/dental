/**
 * Returns the exact wards belonging to a specific local level.
 * Handles duplicate municipality names across different districts.
 * E.g., getWardsForMunicipality('Koshi', 'Bhojpur', 'Bhojpur Municipality') -> ['Ward 1', ..., 'Ward 12']
 */
export function getWardsForMunicipality(province, district, municipality) {
  if (!municipality) return [];
  const compositeKey = `${province}__${district}__${municipality}`;
  const meta = NEPAL_LOCAL_LEVEL_METADATA[compositeKey];
  if (meta && meta.wards) {
    return meta.wards;
  }
  // Fallback: search by district & municipality or just municipality
  for (const [key, val] of Object.entries(NEPAL_LOCAL_LEVEL_METADATA)) {
    if (district && key.includes(`__${district}__${municipality}`)) {
      return val.wards;
    }
  }
  for (const [key, val] of Object.entries(NEPAL_LOCAL_LEVEL_METADATA)) {
    if (key.endsWith(`__${municipality}`)) {
      return val.wards;
    }
  }
  return Array.from({ length: 10 }, (_, i) => `Ward ${i + 1}`);
}

// Fallback general wards array
export const NEPAL_WARDS = Array.from({ length: 35 }, (_, i) => `Ward ${i + 1}`);
